import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import fs from "fs";
import os from "os";
import path from "path";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Track Changes Obsidian Plugin
*/
`;

const prod = process.argv[2] === "production";

const vaultPluginDir =
  process.env.OBSIDIAN_PLUGIN_DIR ||
  path.join(os.homedir(), "NAS/Obsidian/Main/.obsidian/plugins/track-changes");

function syncToVault() {
  try {
    if (!fs.existsSync(vaultPluginDir)) {
      fs.mkdirSync(vaultPluginDir, { recursive: true });
    }
    const stat = fs.lstatSync(vaultPluginDir);
    if (!stat.isSymbolicLink()) {
      fs.copyFileSync("main.js", path.join(vaultPluginDir, "main.js"));
      fs.copyFileSync("manifest.json", path.join(vaultPluginDir, "manifest.json"));
      if (fs.existsSync("styles.css")) {
        fs.copyFileSync("styles.css", path.join(vaultPluginDir, "styles.css"));
      }
      console.log(`[Track Changes] 已直出實體產物至 Vault 外掛目錄: ${vaultPluginDir}`);
    }
  } catch (err) {
    console.warn(`[Track Changes] 同步至 Vault 時發生提醒:`, err.message);
  }
}

const copyPlugin = {
  name: "copy-to-vault",
  setup(build) {
    build.onEnd((result) => {
      if (result.errors.length === 0) {
        syncToVault();
      }
    });
  },
};

const context = await esbuild.context({
  banner: {
    js: banner,
  },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtins,
  ],
  format: "cjs",
  target: "es2021",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  plugins: [copyPlugin],
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
